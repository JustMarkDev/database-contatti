use super::*;

#[derive(Debug, Clone, Serialize)]
pub(crate) struct LeadSource {
    pub(crate) id: &'static str,
    pub(crate) name: &'static str,
    pub(crate) publisher: &'static str,
    pub(crate) landing_url: &'static str,
    pub(crate) license: &'static str,
    pub(crate) coverage: &'static [&'static str],
    /// `si`, `parziale` or `no`: whether the source publishes email addresses.
    pub(crate) emails: &'static str,
    pub(crate) importable: bool,
    pub(crate) note: &'static str,
    /// `dataset` (download and import) or `directory` (crawl a public list of
    /// organizations: emails become leads, linked sites become seeds).
    pub(crate) kind: &'static str,
    /// Taxonomy a directory's leads and seeds inherit.
    pub(crate) category: Option<&'static str>,
    pub(crate) subcategory: Option<&'static str>,
}

pub(super) struct DatasetSpec {
    id: &'static str,
    name: &'static str,
    publisher: &'static str,
    landing_url: &'static str,
    license: &'static str,
    coverage: &'static [&'static str],
    emails: &'static str,
    note: &'static str,
}

pub(super) const fn dataset(spec: DatasetSpec) -> LeadSource {
    let DatasetSpec {
        id,
        name,
        publisher,
        landing_url,
        license,
        coverage,
        emails,
        note,
    } = spec;
    LeadSource {
        id,
        name,
        publisher,
        landing_url,
        license,
        coverage,
        emails,
        importable: true,
        note,
        kind: "dataset",
        category: None,
        subcategory: None,
    }
}

pub(super) const fn directory(
    id: &'static str,
    name: &'static str,
    publisher: &'static str,
    landing_url: &'static str,
    category: &'static str,
    subcategory: &'static str,
    note: &'static str,
) -> LeadSource {
    LeadSource {
        id,
        name,
        publisher,
        landing_url,
        license: "Sito pubblico, nessuna licenza open data",
        coverage: &[],
        emails: "parziale",
        importable: true,
        note,
        kind: "directory",
        category: Some(category),
        subcategory: Some(subcategory),
    }
}

